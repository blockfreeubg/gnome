#!/usr/bin/env node
/**
 * Regenerates RUST_CRATES in src/pages/about/licenses.ts (About → Open-source licenses) from the Rust dependency graph:
 *
 *   node scripts/rust-crates.mjs           rewrite the list between the BEGIN/END markers
 *   node scripts/rust-crates.mjs --check   exit 1 when the list differs from the graph (prints the difference),
 *                                          exit 2 when cargo cannot produce the graph (add --offline to stay offline)
 *
 * The graph is `cargo tree -p gnome-server -e normal` for Linux x86_64 (the crates compiled into gnome-server or
 * used to build it; dev-only crates are not shipped), run from the repository root with `--locked` so a Cargo.lock
 * that needs an update fails instead of being rewritten. Workspace members (gnome-*) are GNOME itself and are left
 * out. Legacy "A/B" license fields are written as "A OR B". New license ids must also be added to LICENSES.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const FILE = fileURLToPath(new URL('../src/pages/about/licenses.ts', import.meta.url));
const BEGIN = '    // BEGIN RUST_CRATES (generated by scripts/rust-crates.mjs; do not edit by hand)';
const END = '    // END RUST_CRATES';

/** Crates as [name, version, license], sorted by name then version. */
export function crateGraph({ offline = false } = {}) {
  const args = ['tree', '-p', 'gnome-server', '-e', 'normal', '--prefix', 'none', '-f', '{p} | {l}', '--target', 'x86_64-unknown-linux-gnu', '--locked'];
  if (offline) args.push('--offline');
  const out = execFileSync('cargo', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  const seen = new Map();
  for (const line of out.split('\n')) {
    // "name vX.Y.Z (path or proc-macro)… | license", with " (*)" appended to repeats of an already listed crate.
    const m = /^(\S+) v(\S+)(?: \([^)]*\))* \| (.*)$/.exec(line.trim().replace(/ \(\*\)$/, ''));
    if (!m) continue;
    const [, name, version, rawLicense] = m;
    if (name.startsWith('gnome-')) continue;
    const license = rawLicense.trim().replace(/\s*\/\s*/g, ' OR ');
    seen.set(`${name}@${version}`, [name, version, license]);
  }
  // Code-unit order (as Array.prototype.sort), so the list stays stable whatever the locale.
  return [...seen.values()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : compareVersions(a[1], b[1])));
}

function compareVersions(a, b) {
  const pa = a.split(/[.+-]/).map((x) => (/^\d+$/.test(x) ? Number(x) : x));
  const pb = b.split(/[.+-]/).map((x) => (/^\d+$/.test(x) ? Number(x) : x));
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const x = pa[i] ?? 0;
    const y = pb[i] ?? 0;
    if (x === y) continue;
    if (typeof x === 'number' && typeof y === 'number') return x - y;
    return String(x).localeCompare(String(y));
  }
  return 0;
}

export function render(crates) {
  return crates.map(([n, v, l]) => `    [${JSON.stringify(n).replace(/"/g, "'")}, '${v}', '${l}'],`).join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  let crates;
  try {
    crates = crateGraph({ offline: process.argv.includes('--offline') });
  } catch (err) {
    // No cargo, no network for --locked resolution, or a Cargo.lock that needs an update: nothing to compare with.
    console.error(`cargo tree failed: ${err instanceof Error ? (err.stderr || err.message).toString().trim() : err}`);
    process.exitCode = 2;
    return;
  }
  const text = readFileSync(FILE, 'utf8');
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < start) throw new Error(`markers not found in ${FILE}`);
  const current = text.slice(start + BEGIN.length + 1, end).trimEnd();
  const next = render(crates);
  if (check) {
    if (current === next) {
      console.log(`RUST_CRATES matches cargo tree (${crates.length} crates).`);
      return;
    }
    const have = new Set(current.split('\n').map((l) => l.trim()));
    const want = new Set(next.split('\n').map((l) => l.trim()));
    for (const l of want) if (!have.has(l)) console.log(`+ ${l}`);
    for (const l of have) if (!want.has(l)) console.log(`- ${l}`);
    console.error('RUST_CRATES is out of date: run node scripts/rust-crates.mjs');
    process.exitCode = 1;
    return;
  }
  writeFileSync(FILE, `${text.slice(0, start + BEGIN.length)}\n${next}\n${text.slice(end)}`);
  console.log(`Wrote ${crates.length} crates to ${FILE}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
